//! Model benchmarking (spec §46): load time, prompt and generation speed, and
//! server RAM for a short fixed prompt, cached per host fingerprint in
//! `cache/hosts/<fingerprint>/benchmarks.json` (spec §98).

use std::{fs, path::PathBuf};

use aidex_core::{CancelToken, Timestamp};
use aidex_host::HostResources;
use serde::{Deserialize, Serialize};

use crate::{
    InferenceError, LocalInference, LocalModelId, Result,
    fsutil::{self, display},
    runtime::RuntimeVariant,
    service::LoadOptions,
};

/// The fixed benchmark prompt.
pub const BENCHMARK_PROMPT: &str =
    "Write a Rust function that returns the sum of a slice of i32 values. Reply with code only.";
/// Tokens generated by the benchmark.
pub const BENCHMARK_TOKENS: u32 = 64;
/// Generation speed at or above which a model is marked recommended for this host.
pub const RECOMMENDED_TOKENS_PER_SECOND: f64 = 5.0;
pub const BENCHMARKS_FILE: &str = "benchmarks.json";
const CACHE_VERSION: u32 = 1;
const MAX_CACHE_BYTES: u64 = 1024 * 1024;

#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct BenchmarkReport {
    pub model: LocalModelId,
    pub sha256: String,
    pub host_fingerprint: String,
    pub runtime: String,
    pub variant: RuntimeVariant,
    pub threads: u32,
    pub ctx_size: u32,
    pub gpu_layers: u32,
    /// Spawn to healthy server (model load), in milliseconds.
    pub load_ms: u64,
    pub prompt_tokens: u64,
    pub prompt_tokens_per_second: f64,
    pub generated_tokens: u64,
    pub generation_tokens_per_second: f64,
    /// Resident memory of the server process tree after the run.
    pub ram_bytes: Option<u64>,
    pub recommended: bool,
    pub measured_at: Timestamp,
    /// Served from the per-host cache rather than measured now.
    pub cached: bool,
}

#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
struct BenchmarkCache {
    version: u32,
    results: Vec<BenchmarkReport>,
}

/// A privacy-preserving host fingerprint (spec §62): a hash of capability
/// characteristics (OS, architecture, CPU model, core counts, RAM rounded to
/// GiB) only, never serial numbers or user data.
pub fn host_fingerprint(resources: &HostResources) -> String {
    let ram_gib = resources
        .total_ram_bytes
        .map_or(0, |bytes| (bytes + (1 << 29)) >> 30);
    let text = format!(
        "aidex-host-v1\n{}\n{}\n{}\n{}\n{}\n{ram_gib}\n",
        std::env::consts::OS,
        std::env::consts::ARCH,
        resources.cpu_brand.as_deref().unwrap_or("unknown"),
        resources.physical_cores.unwrap_or(0),
        resources.logical_cores.unwrap_or(0),
    );
    fsutil::sha256_bytes(text.as_bytes())[..16].to_owned()
}

impl LocalInference {
    fn benchmark_cache_path(&self, fingerprint: &str) -> Result<PathBuf> {
        let paths = self.paths();
        let dir = paths.ensure_dir(&paths.cache().join("hosts").join(fingerprint))?;
        Ok(dir.join(BENCHMARKS_FILE))
    }

    fn cached_benchmarks(&self, path: &PathBuf) -> Vec<BenchmarkReport> {
        let Ok(metadata) = fs::symlink_metadata(path) else {
            return Vec::new();
        };
        if !metadata.is_file() || metadata.len() > MAX_CACHE_BYTES {
            return Vec::new();
        }
        fs::read(path)
            .ok()
            .and_then(|bytes| serde_json::from_slice::<BenchmarkCache>(&bytes).ok())
            .filter(|cache| cache.version == CACHE_VERSION)
            .map(|cache| cache.results)
            .unwrap_or_default()
    }

    /// Benchmark `id` on this host (cached unless `force`).
    pub fn benchmark(
        &self,
        id: &LocalModelId,
        force: bool,
        cancel: &CancelToken,
    ) -> Result<BenchmarkReport> {
        let entry = self.registry().get(id)?;
        let resources = HostResources::current();
        let fingerprint = host_fingerprint(&resources);
        let cache_path = self.benchmark_cache_path(&fingerprint)?;
        let mut results = self.cached_benchmarks(&cache_path);
        if !force {
            if let Some(found) = results
                .iter()
                .find(|report| report.model == entry.id && report.sha256 == entry.sha256)
            {
                let mut found = found.clone();
                found.cached = true;
                return Ok(found);
            }
        }
        let (lease, _) = self.acquire(id, &LoadOptions::default(), cancel)?;
        let model = lease.model();
        if cancel.is_stopped() {
            return Err(InferenceError::Cancelled);
        }
        let timings = model
            .server
            .timed_completion(BENCHMARK_PROMPT, BENCHMARK_TOKENS)?;
        let report = BenchmarkReport {
            model: entry.id.clone(),
            sha256: entry.sha256.clone(),
            host_fingerprint: fingerprint,
            runtime: model.plan.runtime.catalog_id.clone(),
            variant: model.plan.runtime.variant,
            threads: model.plan.threads,
            ctx_size: model.plan.ctx_size,
            gpu_layers: model.plan.gpu_layers,
            load_ms: u64::try_from(model.server.load_time().as_millis()).unwrap_or(u64::MAX),
            prompt_tokens: timings.prompt_tokens,
            prompt_tokens_per_second: timings.prompt_tokens_per_second,
            generated_tokens: timings.generated_tokens,
            generation_tokens_per_second: timings.generation_tokens_per_second,
            ram_bytes: model.server.memory_bytes(),
            recommended: timings.generation_tokens_per_second >= RECOMMENDED_TOKENS_PER_SECOND,
            measured_at: Timestamp::now(),
            cached: false,
        };
        drop(lease);
        results.retain(|other| other.model != report.model);
        results.push(report.clone());
        let json = serde_json::to_vec_pretty(&BenchmarkCache {
            version: CACHE_VERSION,
            results,
        })
        .map_err(|error| InferenceError::Io {
            context: format!("cannot encode {}", display(&cache_path)),
            message: error.to_string(),
        })?;
        fsutil::write_atomic(&cache_path, &json)?;
        Ok(report)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn fingerprints_are_stable_and_ignore_free_memory() {
        let mut resources = HostResources {
            total_ram_bytes: Some(16 * (1 << 30) - 100),
            available_ram_bytes: Some(1 << 30),
            physical_cores: Some(8),
            logical_cores: Some(16),
            cpu_brand: Some("CPU".into()),
        };
        let first = host_fingerprint(&resources);
        resources.available_ram_bytes = Some(5 << 30);
        assert_eq!(host_fingerprint(&resources), first);
        assert_eq!(first.len(), 16);
        resources.physical_cores = Some(4);
        assert_ne!(host_fingerprint(&resources), first);
    }
}
